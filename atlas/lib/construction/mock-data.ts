// ---- Units for Job 001 (Millbrook Crossing Phase 2) ----
function generateUnitsForJob001(): Unit[] {
  const plans = [
    { name: "The Ashford", specs: "4BR/3BA, 2,450 SF", budget: 365000 },
    { name: "The Beaumont", specs: "3BR/2.5BA, 2,100 SF", budget: 325000 },
    { name: "The Crestview", specs: "4BR/3.5BA, 2,800 SF", budget: 410000 },
    { name: "The Dunmore", specs: "3BR/2BA, 1,850 SF", budget: 295000 },
  ]

  return Array.from({ length: 24 }, (_, i) => {
    const num = i + 1
    const plan = plans[i % plans.length]
    const phase = num <= 6 ? 16 : num <= 12 ? 9 + Math.floor((num - 6) / 2) : num <= 18 ? 4 + Math.floor((num - 12) / 2) : 1 + Math.floor((num - 18) / 3)
    const isComplete = num <= 6
    const isNotStarted = num > 20

    let scheduleStatus: Unit["schedule_status"] = "on_schedule"
    if (isComplete) scheduleStatus = "complete"
    else if (isNotStarted) scheduleStatus = "not_started"
    else if (num === 8 || num === 14) scheduleStatus = "behind_1_7"
    else if (num === 10) scheduleStatus = "behind_8_plus"

    const committed = isComplete ? plan.budget * 0.98 : plan.budget * (phase / 16) * 0.85
    const actual = isComplete ? plan.budget * 0.96 : committed * 0.9

    return {
      id: `unit-001-${String(num).padStart(3, "0")}`,
      job_id: "job-001",
      unit_number: `MC2-${String(num).padStart(3, "0")}`,
      address: `${100 + num} Millbrook Crossing Dr, Greenville, SC 29607`,
      floor_plan_name: plan.name,
      floor_plan_specs: plan.specs,
      upgrade_package: num % 3 === 0 ? "Premium Plus" : num % 2 === 0 ? "Standard Upgrade" : undefined,
      current_phase: isComplete ? 16 : isNotStarted ? 0 : phase,
      permit_date: isNotStarted ? undefined : "2025-04-10",
      construction_start: isNotStarted ? undefined : "2025-05-01",
      projected_completion: isNotStarted ? undefined : isComplete ? "2025-12-15" : "2026-06-30",
      co_date: isComplete ? "2025-12-10" : undefined,
      total_budget: plan.budget,
      committed: Math.round(committed),
      actual: Math.round(actual),
      status: isComplete ? "complete" : isNotStarted ? "not_started" : "in_progress",
      schedule_status: scheduleStatus,
      created_at: "2025-03-15T10:00:00Z",
    }
  })
}

