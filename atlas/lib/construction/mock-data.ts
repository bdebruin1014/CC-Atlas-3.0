// ---- Milestones for a specific unit (MC2-007, in-progress at phase 10) ----
export function generateMilestones(unitId: string, currentPhase: number): Milestone[] {
  const baseDate = new Date("2025-05-01")
  return CONSTRUCTION_PHASES.map((phase) => {
    const plannedStart = new Date(baseDate)
    plannedStart.setDate(baseDate.getDate() + (phase.number - 1) * 14)
    const plannedEnd = new Date(plannedStart)
    plannedEnd.setDate(plannedStart.getDate() + 12)

    let status: Milestone["status"] = "not_started"
    let actualStart: string | undefined
    let actualEnd: string | undefined
    let actualDuration: number | undefined

    if (phase.number < currentPhase) {
      status = "completed"
      const aStart = new Date(plannedStart)
      aStart.setDate(aStart.getDate() + Math.floor(Math.random() * 3) - 1)
      actualStart = aStart.toISOString().split("T")[0]
      const aEnd = new Date(plannedEnd)
      aEnd.setDate(aEnd.getDate() + Math.floor(Math.random() * 5) - 2)
      actualEnd = aEnd.toISOString().split("T")[0]
      actualDuration = Math.round(
        (new Date(actualEnd).getTime() - new Date(actualStart).getTime()) /
          (1000 * 60 * 60 * 24)
      )
    } else if (phase.number === currentPhase) {
      status = "in_progress"
      const aStart = new Date(plannedStart)
      aStart.setDate(aStart.getDate() + 1)
      actualStart = aStart.toISOString().split("T")[0]
    }

    const requiredInspections = PHASE_INSPECTIONS[phase.number] || []
    const inspections: Inspection[] = requiredInspections.map((type, idx) => ({
      id: `insp-${unitId}-${phase.number}-${idx}`,
      unit_id: unitId,
      milestone_id: `ms-${unitId}-${phase.number}`,
      phase_number: phase.number,
      type,
      scheduled_date: plannedEnd.toISOString().split("T")[0],
      actual_date:
        phase.number < currentPhase
          ? plannedEnd.toISOString().split("T")[0]
          : undefined,
      result: phase.number < currentPhase ? "pass" : undefined,
      inspector: phase.number < currentPhase ? "Greenville County" : undefined,
      municipality: "Greenville County",
      notes: undefined,
      is_required: true,
      is_reinspection: false,
    }))

    return {
      id: `ms-${unitId}-${phase.number}`,
      unit_id: unitId,
      phase_number: phase.number,
      phase_name: phase.name,
      status,
      planned_start: plannedStart.toISOString().split("T")[0],
      planned_end: plannedEnd.toISOString().split("T")[0],
      actual_start: actualStart,
      actual_end: actualEnd,
      planned_duration: 12,
      actual_duration: actualDuration,
      inspections,
    }
  })
}

