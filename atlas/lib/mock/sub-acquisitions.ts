// Compute aggregate financials from sub-acquisition array
export function computeSubAcquisitionAggregates(subs: SubAcquisition[]) {
  const active = subs.filter((s) => s.status !== "dropped")
  const statusBreakdown = {} as Record<string, number>
  for (const s of subs) {
    statusBreakdown[s.status] = (statusBreakdown[s.status] || 0) + 1
  }

  const totalPurchase = active.reduce((s, a) => s + (a.purchase_price ?? 0), 0)
  const totalSale = active.reduce((s, a) => s + (a.projected_sale_price ?? 0), 0)
  const totalProfit = active.reduce((s, a) => s + (a.projected_profit ?? 0), 0)

  return {
    total_properties: subs.length,
    active_properties: active.length,
    total_purchase_price: totalPurchase,
    total_sale_price: totalSale,
    total_projected_profit: totalProfit,
    weighted_avg_margin: totalSale > 0 ? (totalProfit / totalSale) * 100 : 0,
    total_acreage: active.reduce((s, a) => s + (a.acreage ?? 0), 0),
    total_lots: active.reduce((s, a) => s + (a.lot_count ?? 0), 0),
    total_earnest_money: active.reduce((s, a) => s + (a.earnest_money ?? 0), 0),
    total_dd_fees: active.reduce((s, a) => s + (a.due_diligence_fee ?? 0), 0),
    status_breakdown: statusBreakdown,
  }
}
